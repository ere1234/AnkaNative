#!/usr/bin/env python3
# Compiles the graphics selftest's shaders (tri.vert, tri.frag, fill.comp: GLSL written for the shader library's descriptor ABI, not game code) to SPIR-V 1.3 with glslangValidator
# and writes them as word arrays into ../vka_selftest_spv.h, which vka_selftest.c includes (and nanscan*.comp, the DM_VK_NANSCAN / DM_VK_NANSCAN_CS diagnostics of vka_nanscan.c; ndsr.comp, vka_draw.c's DM_VK_NDSR_STANDIN).
# meshemu.comp (vka_draw.c's mesh draws as compute) goes into ../vka_meshemu_spv.h. Arguments: the headers to write (default all). Run it after changing a shader; needs glslangValidator and spirv-val on PATH
import os, struct, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = [("tri.vert", "SPV_TRI_VERT"), ("tri.frag", "SPV_TRI_FRAG"), ("fill.comp", "SPV_FILL_COMP"), ("nanscan.comp", "SPV_NANSCAN_COMP"), ("nanscan3.comp", "SPV_NANSCAN3_COMP"), ("fetch.comp", "SPV_FETCH_COMP"),
           ("nanscan_cs.comp", "SPV_NANSCAN_CS_COMP"), ("nanscan_9e5.comp", "SPV_NANSCAN_9E5_COMP"), ("ndsr.comp", "SPV_NDSR_COMP")]
# meshemu.comp: the passes around a task / mesh draw on a device without mesh shading (vka_draw.c "Mesh draws as compute"), in a header of its own
HEADERS = [("vka_selftest_spv.h", SHADERS, "the graphics selftest's shaders"), ("vka_meshemu_spv.h", [("meshemu.comp", "SPV_MESHEMU_COMP")], "the mesh draws' prep and scan passes")]

def main():
    want = sys.argv[1:]   # header names to write (default: all)
    for header, shaders, what in HEADERS:
        if not want or header in want: write(header, shaders, what)
    return 0

def write(header, shaders, what):
    out = ["// Generated by dm/gfx/vk_android/selftest/spv.py from the GLSL beside it (glslangValidator -V --target-env vulkan1.1 -g0): %s. Do not edit" % what,
           "#pragma once", "#include <stdint.h>"]
    with tempfile.TemporaryDirectory() as tmp:
        for src, name in shaders:
            spv = os.path.join(tmp, src + ".spv")
            subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1", "-g0", "-o", spv, os.path.join(HERE, src)], check=True, stdout=subprocess.DEVNULL)
            subprocess.run(["spirv-val", "--target-env", "vulkan1.1", spv], check=True)
            data = open(spv, "rb").read()
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            out.append("static const uint32_t %s[%d] = {" % (name, len(words)))
            for i in range(0, len(words), 12):
                out.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 12]) + ",")
            out.append("};")
    open(os.path.join(HERE, "..", header), "w").write("\n".join(out) + "\n")

if __name__ == "__main__":
    sys.exit(main())
